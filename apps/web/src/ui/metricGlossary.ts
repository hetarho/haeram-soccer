/** Which glossary sheet is open: one entry, all entries, or none. */
export const useGlossary = create<{ open?: string; show: (id?: string) => void; hide: () => void }>(
  (set) => ({
    show: (id = 'all') => set({ open: id }),
    hide: () => set({ open: undefined }),
  }),
);
