const stages = [], started = new Date().toISOString();
function run(stage, args, env = process.env) {
  const start = performance.now(), at = new Date().toISOString();
  const result = spawnSync('pnpm', args, { stdio: 'inherit', env });
  stages.push({ stage, command: 'pnpm ' + args.join(' '), started: at, finished: new Date().toISOString(), elapsedMs: Math.round(performance.now() - start), exitCode: result.status });
  writeFileSync('.tmp/hr05-sync-steps.json', JSON.stringify({ source: pinned, stages }, null, 2) + '\n');
  assert.equal(result.status, 0, stage);
}
for (const stage of ['typecheck', 'lint', 'format:check']) run(stage, ['run', stage]);
