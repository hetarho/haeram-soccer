function rows(report) {
  const all = [];
  function walk(suites, titles = [], depth = 0) {
    for (const suite of suites) {
      const path = depth ? [...titles, suite.title] : titles;
      for (const spec of suite.specs ?? []) for (const test of spec.tests) all.push({ file: spec.file, project: test.projectName, titles: [...path, spec.title], key: [test.projectName, spec.file, ...path, spec.title].join('\0'), status: test.status, results: test.results });
      walk(suite.suites ?? [], path, depth + 1);
    }
  }
  walk(report.suites);
  return all;
}
